function deepMerge(baseObj, over) {
  if (over === undefined || over === null) return baseObj;
  if (Array.isArray(over)) return over;
  if (typeof over !== "object") return over;
  const out = { ...baseObj };
  for (const k of Object.keys(over)) {
    const bv = baseObj?.[k];
    const ov = over[k];
    if (Array.isArray(ov)) {
      out[k] = ov;
      continue;
    }
    if (bv !== undefined && typeof bv === "object" && !Array.isArray(bv) && typeof ov === "object" && !Array.isArray(ov)) {
      out[k] = deepMerge(bv, ov);
    } else {
      out[k] = ov;
    }
  }
  return out;
}

